// T4（2026-08-23，第五轮实测）—— **引文只有一把尺子。**
//
// 一条更正带着 `corrected_quote`：新块更正的是旧块里的哪一句。它进库之前过一道闸
// （`api_engine.rs::gate_proposals` → `locate`），那道闸**折叠全角/半角标点**才放行；
// 而屏幕上和 pack 里找这句话，用的是 `content.includes(quote)` —— **不折叠**。
//
// ⛔ 两把尺子平常不咬人，但有一条路会：**先接受一条更正，之后再压缩这个项目。**
// 压缩会顺手把全角标点换成半角（实测〈申请规划〉那一份换掉了 46%：1,049 → 566），
// R1 之后压缩稿**写回 `content`** —— 于是存好的引文从此对不上，
// **那句高亮悄悄消失，界面不报任何错，pack 里那行「更正了哪一句」也退回只报块号。**
//
// ⚠️ 折叠表和 Rust 那张**必须逐项一致**（`api_engine.rs::fold_char`），
// `quoteFold.test.ts` 钉着字符数。两边各写一遍是认了的代价（和表头双份同一类），
// ⛔ 但改一边不改另一边，就又回到两把尺子。

/** 全角 → 半角，**只有标点**。⛔ 数字一个都不在这儿：全角 ０-９ 故意不折叠 ——
 *  「这个数字被重打过」和「这个标点被重打过」是两件事，前者必须报出来。
 *
 *  ⚠️ 每一项都是**单字符对单字符**（长度守恒）。这一条是整个模块成立的前提：
 *  折叠之后算出来的偏移，可以原样拿回**没折叠**的正文上用。
 *  ⚠️ `…` 故意不在表里 —— 提示词明写「不许用省略号」，它是破规矩，不是重打。 */
const FOLD: Record<string, string> = {
  '，': ',', '、': ',',
  '。': '.', '．': '.',
  '；': ';',
  '：': ':',
  '！': '!',
  '？': '?',
  '（': '(',
  '）': ')',
  '《': '<',
  '》': '>',
  '【': '[',
  '】': ']',
  '“': '"', '”': '"', '「': '"', '」': '"', '『': '"', '』': '"',
  '‘': "'", '’': "'",
  '—': '-', '–': '-', '－': '-', '﹣': '-', '‐': '-',
  '／': '/',
  '＼': '\\',
  '｜': '|',
  '～': '~',
  '％': '%',
  '＃': '#',
  '＆': '&',
  '＊': '*',
  '＋': '+',
  '＝': '=',
  '＄': '$',
  '　': ' ',
};

const FOLD_RE = new RegExp(`[${Object.keys(FOLD).join('')}]`, 'g');

/** ⚠️ 长度守恒：表里每一项都是 BMP 单码元 → ASCII 单码元，所以折叠前后
 *  `s.length` 一模一样，折叠串上的下标可以直接当原串的下标用。 */
export const foldPunctuation = (s: string): string => s.replace(FOLD_RE, (c) => FOLD[c]);

/** 这句引文在这一块正文里的位置（**标点按闸门那套折叠之后**比）。找不到返回 -1。
 *
 *  ⚠️ 返回的是**原文**里的下标 —— 折叠长度守恒，两边是同一套坐标。 */
export const locateQuote = (content: string, quote: string, from = 0): number => {
  if (quote === '') return -1;
  return foldPunctuation(content).indexOf(foldPunctuation(quote), from);
};

/** 这句引文还在不在这一块里。⭐ 「更正指到哪一句」这件事，全库只问这一个函数。 */
export const quoteIsInBlock = (content: string, quote: string): boolean =>
  locateQuote(content, quote) !== -1;
