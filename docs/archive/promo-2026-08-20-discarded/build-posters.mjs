const esc = (s) => s ?? '';

for (const p of posters) {
  const words = `<h1>${p.h1}</h1>
       ${p.sub ? `<div class="sub">${p.sub}</div>` : ''}
       ${p.strip ? `<div class="strip"><span class="dot"></span>${p.strip}</div>` : ''}`;

  const eyebrow = p.eyebrow ? `<div class="eyebrow">${p.eyebrow}</div>` : '';
  const against = p.against
    ? `<div class="against"><div class="n${p.against.n.length > 4 ? ' long' : ''}">${p.against.n}</div><div class="t">${p.against.t}</div></div>` : '';
  const sub = p.sub ? `<div class="sub">${p.sub}</div>` : '';
  const art = p.id.endsWith('-en') ? artifactEN : artifactZH;

  const body = p.figure
    ? (p.size === 'w'
        // 16:9 has no room for a stacked column under a 236px numeral — split it
        ? `<div><div class="figure">${p.figure}</div><div class="lede">${p.lede}</div></div>
           <div>${eyebrow}${against}${sub}</div>`
        : `${eyebrow}<div class="figure">${p.figure}</div>
           <div class="lede">${p.lede}</div>${against}${sub}`)
    : p.outro
      ? `<div class="outro">${mark}<h1>${p.h1}</h1><div class="lede">${p.lede}</div>
         ${p.strip ? `<div class="strip"><span class="dot"></span>${p.strip}</div>` : ''}</div>`
      : p.size === 'w' ? `<div>${words}</div>${art}` : `${art}${words}`;

  const html = `<!doctype html><meta charset="utf-8">
<title>${p.id}</title>
<link rel="stylesheet" href="poster.css">
<div class="poster ${p.size}">
  ${coil(p.coil)}
  <div class="top">
    <div class="brand">${mark}<b>Spool<span> 思簿</span></b></div>
    <div class="kicker">${esc(p.kicker)}</div>
  </div>
  <div class="mid ${p.outro ? 'centre' : p.figure ? (p.size === 'w' ? 'fig' : '') : (p.size === 'w' ? 'split' : '')}">
    ${body}
  </div>
  <div class="bot">
    <div class="proof">
      ${p.proofLabel ? `<span class="lbl">${p.proofLabel}</span>` : ''}
      ${p.cmd ? `<span class="cmd">${p.cmd}</span>` : ''}
    </div>
    <div class="site">${p.site}</div>
  </div>
</div>`;
  writeFileSync(join(here, `poster-${p.id}.html`), html);
}
